import type { Asset, Category } from "../../types/asset";
import { artSize, renderArt, type ArtKind } from "../art/generate";

const KIND: Record<Category, ArtKind> = {
  tileset: "tileset",
  "sprite-pack": "sprites",
  "sprite-sheet": "sprites",
  "ui-kit": "ui",
  "icon-pack": "icons",
};

function make(
  n: number,
  title: string,
  category: Category,
  price: number,
  editionLimit: number | null,
  soldCount: number,
  creatorName: string,
  description: string,
  extra: Partial<Asset> = {},
): Asset {
  const kind = KIND[category];
  const seeds = [n * 17 + 1, n * 17 + 2];
  const [w, h] = artSize(kind, seeds[0]);
  return {
    id: `a${n}`,
    title,
    description,
    creatorId: creatorName.toLowerCase(),
    creatorName,
    category,
    price,
    currency: "USD",
    editionLimit,
    soldCount,
    status: "published",
    previewImages: seeds.map(
      (s) =>
        `data:image/svg+xml;utf8,${encodeURIComponent(renderArt(kind, s))}`,
    ),
    previewAspect: Math.round((w / h) * 100) / 100,
    fileFormats: ["PNG"],
    compatibleWith: ["Godot", "Unity", "GameMaker"],
    createdAt: `2026-10-${String(10 + n).padStart(2, "0")}T10:00:00Z`,
    updatedAt: `2026-10-${String(10 + n).padStart(2, "0")}T10:00:00Z`,
    ...extra,
  };
}

